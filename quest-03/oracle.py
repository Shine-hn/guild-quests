"""The Silent Oracle of the Guild. It answers only when you call it in the right way.

Do not edit this file. Read its help instead:

  python oracle.py --help
"""
import argparse
import base64
import os
import sys

VOICES = {"murmur": "mmmm...", "chant": "oh-oh-ohm...", "song": "la-la-laaa..."}
OFFERING = "bGFudGVybg=="
WORDS = {"ask": "ZWNobw==", "listen": "ZGVwdGhz"}

EPILOG = """\
Environment variables:
  ORACLE_MODE=deep   let the oracle speak with its deep voice (listen only)

Run 'python oracle.py COMMAND --help' to see the options of each command."""


def decode(text):
    return base64.b64decode(text).decode()


def build_parser():
    parser = argparse.ArgumentParser(
        prog="oracle.py",
        description="The Silent Oracle of the Guild. It answers only when you call it in the right way.",
        epilog=EPILOG,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument("--voice", choices=sorted(VOICES), default="murmur",
                        help="how the oracle speaks (default: %(default)s)")
    commands = parser.add_subparsers(dest="command", required=True, title="commands")

    ask = commands.add_parser("ask", help="ask the oracle a question",
                              description="Ask the oracle a question about the past or the future.")
    loudness = ask.add_mutually_exclusive_group()
    loudness.add_argument("--loud", action="store_true", help="ask in a loud voice")
    loudness.add_argument("--soft", action="store_true", help="ask in a soft voice")
    ask.add_argument("--offering", metavar="ITEM",
                     help="a gift for the oracle; it accepts only the light that never goes out "
                          "(you found it behind the first gate of the Guild)")
    ask.add_argument("time", choices=["past", "future"], help="ask about the past or the future")
    ask.add_argument("word", nargs="+", help="the words of your question")

    commands.add_parser("listen", help="listen to the oracle",
                        description="Sit down and listen to the oracle.")
    return parser


def ask(args):
    question = " ".join(args.word)
    print(f"You ask about the {args.time}: \"{question}\"")
    if args.loud:
        print("Your voice echoes in the hall.")
    elif args.soft:
        print("You whisper.")
    if args.offering is None:
        print("The oracle does not move. It seems to want something from you.")
        return 1
    if args.offering.strip().lower() != decode(OFFERING):
        print(f"You give the oracle a {args.offering}. The oracle looks at it and shakes its head.")
        return 1
    print("The oracle takes the light. Its eyes open, and it speaks one word.")
    print(f"The word is: {decode(WORDS['ask'])}")
    return 0


def listen(args):
    mode = os.environ.get("ORACLE_MODE")
    if mode is None:
        print(f"You listen. The oracle makes only a quiet {args.voice}: \"{VOICES[args.voice]}\"")
        print("It has a deeper voice, but you cannot hear it now.")
        return 1
    if mode.strip().lower() != "deep":
        print(f"ORACLE_MODE is '{mode}'. The oracle does not know this mode.")
        return 1
    print("The floor shakes. A deep voice comes from far below.")
    print(f"The word is: {decode(WORDS['listen'])}")
    return 0


def main():
    args = build_parser().parse_args()
    if args.command == "ask":
        return ask(args)
    return listen(args)


if __name__ == "__main__":
    sys.exit(main())
